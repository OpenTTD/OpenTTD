/// The OpenTTD configuration a compiled scenario assumes, as an openttd.cfg fragment.
pub fn cfg_fragment(sc: &Scenario) -> String {
    let mut out = String::from("; RESEARCH-ONLY. Generated by rw-scenario; the settings the heightmap and GameScript assume.\n");
    let mut section = String::new();
    for (k, v) in &sc.settings {
        let (sec, key) = k.split_once('.').unwrap();
        if sec != section {
            out.push_str(&format!("\n[{sec}]\n"));
            section = sec.to_string();
        }
        out.push_str(&format!("{key} = {v}\n"));
    }
    out.push_str(&format!("\n[game_scripts]\n{} = \n", gamescript::NAME));
    out
}

/// The notice that travels with the artifacts. Names, positions and the town and industry lists
/// come from OpenStreetMap, so this directory is an ODbL 1.0 derivative database; the heightmap
/// is a modified Copernicus DEM product.
pub fn attribution_file(sc: &Scenario, snap: &Snapshot) -> String {
    let mut o = format!(
        "Real-world scenario of \"{}\" ({}), compiled by rw-scenario {} (RESEARCH-ONLY).\n\n\
         The town and industry names and positions, the landmark signs, towns.json, scenario.json and the\n\
         GameScript's data are derived from OpenStreetMap data and are made available under the Open Database\n\
         License 1.0 (ODbL): https://opendatacommons.org/licenses/odbl/1-0/ . They are not covered by the\n\
         repository's code licence. Map data © OpenStreetMap contributors, https://www.openstreetmap.org/copyright\n\n",
        sc.query, sc.chosen, sc.tool.version
    );
    for s in &snap.sources {
        o.push_str(&format!("- {} ({}), retrieved {}\n  licence: {}\n  attribution: {}\n", s.provider, s.layer, s.retrieved_at, s.license, s.attribution));
    }
    o.push_str("\nGame roles, positions and links are DERIVED, INFERRED or HYPOTHETICAL as scenario.json says for each;\n\
                none is a claim about a real business, its output or its operation. A HYPOTHETICAL industry named\n\
                \"(gameplay stand-in at ...)\" only takes the position of a mapped site; the site is not evidence for it.\n\
                Towns the game generates on its own are renamed \"Generated town <n>\" and are not real places.\n\
                Whoever redistributes this directory, changed or not, passes on these notices: Subsequent Users are\n\
                bound by the same obligations (ODbL 1.0 share-alike; Copernicus DEM GLO-30-F licence Art. 6(e)).\n");
    o
}

/// Write every artifact of a compiled scenario into `out` and return the final scenario
/// (with its artifact list). Same inputs, same bytes.
pub fn write_outputs(out: &Path, mut c: compile::Compiled, snap: &Snapshot, rules: &rules::Rules) -> Result<Scenario, String> {
    let gs_dir = out.join("game").join(gamescript::NAME);
    std::fs::create_dir_all(&gs_dir).map_err(|e| format!("{}: {e}", gs_dir.display()))?;
    let sc = &c.scenario;
    let files: Vec<(String, Vec<u8>, &str)> = vec![
        ("heightmap.png".into(), c.heightmap_png.clone(), "OpenTTD heightmap (8-bit grey, rotation clockwise); load with -g"),
        ("towns.json".into(), snapshot::to_bytes(&gamescript::town_data(sc)), "OpenTTD town data for the Scenario Editor's Load town data (docs/importing_town_data.md)"),
        (format!("game/{}/info.nut", gamescript::NAME), gamescript::info_nut(sc).into_bytes(), "GameScript info"),
        (format!("game/{}/main.nut", gamescript::NAME), gamescript::main_nut(sc, rules).into_bytes(), "GameScript placing towns, industries and signs through the Script API"),
        ("openttd.cfg".into(), cfg_fragment(sc).into_bytes(), "openttd.cfg fragment of the settings the scenario assumes"),
        ("ATTRIBUTION.txt".into(), attribution_file(sc, snap).into_bytes(), "sources, licences and attribution of everything in this directory"),
        ("preview.svg".into(), preview::svg(sc, snap, &c.heightmap_png).into_bytes(), "static review image of terrain, entities and links by evidence class"),
    ];
    let mut artifacts = Vec::new();
    for (name, bytes, purpose) in &files {
        std::fs::write(out.join(name), bytes).map_err(|e| format!("{name}: {e}"))?;
        artifacts.push(Artifact { file: name.clone(), sha256: net::sha256_hex(bytes), purpose: purpose.to_string() });
    }
    c.scenario.artifacts = artifacts;
    let bytes = snapshot::to_bytes(&c.scenario);
    std::fs::write(out.join("scenario.json"), &bytes).map_err(|e| format!("scenario.json: {e}"))?;
    let mut sums = String::new();
    for a in &c.scenario.artifacts {
        sums.push_str(&format!("{}  {}\n", a.sha256, a.file));
    }
    sums.push_str(&format!("{}  scenario.json\n", net::sha256_hex(&bytes)));
    std::fs::write(out.join("SHA256SUMS"), sums).map_err(|e| format!("SHA256SUMS: {e}"))?;
    Ok(c.scenario)
}
