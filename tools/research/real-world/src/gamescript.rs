//! The GameScript the compiler writes: the supported, headless way to put towns, industries and
//! signs on a heightmap game. It runs inside the game as a deity script and changes the world
//! only through the Script API (`GSTown.FoundTown`, `GSTown.ExpandTown`,
//! `GSIndustryType.BuildIndustry`, `GSSign.BuildSign`), which issue the game's own commands, so
//! placement is deterministic for a given seed and safe in multiplayer.
//!
//! It resolves every industry role against the running game by cargo labels (an industry type
//! whose produced and accepted cargo labels equal the role's), so it never trusts a type number,
//! and logs every outcome with the prefix `rw:` (read back by `rw-scenario load-check`).

use crate::model::{Entity, Scenario};
use crate::rules::Rules;

pub const NAME: &str = "RealWorldScenario";

/// OpenTTD reads a script file as UTF-8 only when it starts with a byte-order mark; without one it
/// reads every byte as a character of its own (src/script/squirrel.cpp, `Squirrel::LoadFile`,
/// `_io_file_lexfeed_ASCII`), so every non-ASCII town or sign name would be garbled in the game.
pub const UTF8_BOM: &str = "\u{FEFF}";

fn q(s: &str) -> String {
    let mut o = String::from("\"");
    for c in s.chars() {
        match c {
            '\\' => o.push_str("\\\\"),
            '"' => o.push_str("\\\""),
            '\n' => o.push_str("\\n"),
            c if (c as u32) < 0x20 => {}
            c => o.push(c),
        }
    }
    o.push('"');
    o
}

fn list(v: &[String]) -> String {
    format!("[{}]", v.iter().map(|s| q(s)).collect::<Vec<_>>().join(", "))
}

pub fn info_nut(sc: &Scenario) -> String {
    format!(
        r#"{UTF8_BOM}/* RESEARCH-ONLY. Generated by rw-scenario {ver} from snapshot {snap}; do not edit, recompile. */
class RealWorldScenario extends GSInfo {{
	function GetAuthor()      {{ return "rw-scenario (research fork)"; }}
	function GetName()        {{ return "{NAME}"; }}
	function GetShortName()   {{ return "RWSC"; }}
	function GetDescription() {{ return {desc}; }}
	function GetVersion()     {{ return 1; }}
	function GetAPIVersion()  {{ return "17"; }}
	function GetDate()        {{ return "2026-11-18"; }}
	function CreateInstance() {{ return "RealWorldScenario"; }}
	function UseAsRandomAI()  {{ return false; }}
}}

RegisterGS(RealWorldScenario());
"#,
        ver = sc.tool.version,
        snap = &sc.snapshot_sha256[..16.min(sc.snapshot_sha256.len())],
        desc = q(&format!("Places the towns, industries and landmarks compiled for '{}' ({}). Evidence classes are in scenario.json.", sc.query, sc.chosen)),
    )
}

/// What the game shows for an entity (town and industry text): its evidence class, its evidence
/// and anchor records and its rule, so a player can tell a mapped fact from a stand-in.
pub fn note(e: &Entity) -> String {
    let ev = format!("{:?}", e.evidence).to_uppercase();
    let mut n = format!("{ev} · evidence {} · anchor {} · rule {}",
        e.evidence_feature.as_deref().unwrap_or("none"), e.anchor_feature.as_deref().unwrap_or("none"), e.rule);
    if e.evidence == crate::model::Evidence::Hypothetical {
        n.push_str(" · gameplay stand-in or invented for playability, not a real business");
    }
    n
}

fn entity_row(e: &Entity) -> String {
    format!(
        "\t{{ id = {}, kind = {}, role = {}, name = {}, x = {}, y = {}, pop = {}, city = {}, evidence = {}, note = {}, sx0 = {}, sy0 = {}, sx1 = {}, sy1 = {} }},\n",
        q(&e.id),
        q(&e.game.kind),
        q(&e.game.role),
        q(&e.name),
        e.tile.x,
        e.tile.y,
        e.population.unwrap_or(0),
        e.city,
        q(&format!("{:?}", e.evidence).to_uppercase()),
        q(&note(e)),
        e.site.as_ref().map(|b| b.x0 as i64).unwrap_or(-1),
        e.site.as_ref().map(|b| b.y0 as i64).unwrap_or(-1),
        e.site.as_ref().map(|b| b.x1 as i64).unwrap_or(-1),
        e.site.as_ref().map(|b| b.y1 as i64).unwrap_or(-1)
    )
}

pub fn main_nut(sc: &Scenario, r: &Rules) -> String {
    let mut rows = String::new();
    // Towns first (industries keep their distance from them), then industries, then signs.
    for kind in ["town", "industry", "sign"] {
        for e in sc.entities.iter().filter(|e| e.game.kind == kind) {
            rows.push_str(&entity_row(e));
        }
    }
    let mut roles = String::new();
    for (name, role) in &r.profile.industries {
        roles.push_str(&format!("\t{} = {{ produces = {}, accepts = {} }},\n", name, list(&role.produces), list(&role.accepts)));
    }
    format!(
        r#"{UTF8_BOM}/* RESEARCH-ONLY. Generated by rw-scenario {ver} from snapshot {snap} and rules {rules}@{rv}; do not edit, recompile.
 * Changes the world only through the Script API, i.e. the game's own commands (deity mode). */

ATTRIBUTION <- {attr};

ENTITIES <- [
{rows}];

ROLES <- {{
{roles}}};

function Labels(list) {{
	local out = [];
	foreach (c, _ in list) out.append(GSCargo.GetCargoLabel(c));
	out.sort();
	return out;
}}

function Same(a, b) {{
	local x = clone a; x.sort();
	if (x.len() != b.len()) return false;
	for (local i = 0; i < x.len(); i++) if (x[i] != b[i]) return false;
	return true;
}}

/* Deterministic outward ring of offsets: (0,0), then rings of radius 1..r. */
function Ring(r) {{
	local out = [[0, 0]];
	for (local d = 1; d <= r; d++) {{
		for (local dx = -d; dx <= d; dx++) for (local dy = -d; dy <= d; dy++) {{
			if (Max(Abs(dx), Abs(dy)) == d) out.append([dx, dy]);
		}}
	}}
	return out;
}}

/* The entity's note, and how far the game moved it from its anchor when it did. */
/* The note's distance comes from where the game really put the entity (its location tile), never
 * from the offset tried: an index outside the map would name another tile. */
function Site(e, x, y) {{
	if (e.sx0 < 0) return "none";
	return (x >= e.sx0 - 1 && x <= e.sx1 + 1 && y >= e.sy0 - 1 && y <= e.sy1 + 1) ? "at" : "outside";
}}
function Note(e, x, y) {{
	local d = Abs(x - e.x) + Abs(y - e.y);
	local site = Site(e, x, y);
	if (site == "outside") return e.note + " · relocated outside its mapped site, " + d + " tiles from its anchor";
	if (d > 0 && site == "at") return e.note + " · placed " + d + " tiles from its anchor, still within its mapped site";
	return d > 0 ? e.note + " · placed " + d + " tiles from its anchor" : e.note;
}}
function OnMap(x, y) {{ return x >= 0 && y >= 0 && x < GSMap.GetMapSizeX() && y < GSMap.GetMapSizeY(); }}

function Max(a, b) {{ return a > b ? a : b; }}
function Abs(a) {{ return a < 0 ? -a : a; }}

class RealWorldScenario extends GSController {{
	/* Placement happens once per game: a saved game remembers it, so a reload never places again. */
	placed = false;
	function Start();
	function Save() {{ return {{ placed = this.placed }}; }}
	function Load(version, data) {{ if ("placed" in data) this.placed = data.placed; }}
}}

function RealWorldScenario::Start()
{{
	GSLog.Info("rw: start " + ENTITIES.len() + " entities");
	/* Attribution in the game view, as the sources' terms ask of a game (OSMF attribution guideline). */
	if (this.placed) {{
		GSLog.Info("rw: resumed placed=true game_towns " + GSTownList().Count() + " game_industries " + GSIndustryList().Count() + " game_signs " + GSSignList().Count());
		while (true) this.Sleep(740);
	}}
	GSNews.Create(GSNews.NT_GENERAL, ATTRIBUTION, GSCompany.COMPANY_INVALID, GSNews.NR_NONE, 0);
	GSLog.Info("rw: attribution " + ATTRIBUTION);
	local types = {{}};
	foreach (name, role in ROLES) {{
		local want_p = clone role.produces; want_p.sort();
		local want_a = clone role.accepts; want_a.sort();
		local found = null;
		foreach (t, _ in GSIndustryTypeList()) {{
			if (Same(Labels(GSIndustryType.GetProducedCargo(t)), want_p) && Same(Labels(GSIndustryType.GetAcceptedCargo(t)), want_a) && GSIndustryType.CanBuildIndustry(t)) {{
				found = t; break;
			}}
		}}
		if (found == null) GSLog.Warning("rw: role " + name + " UNRESOLVED in this game");
		else {{ types[name] <- found; GSLog.Info("rw: role " + name + " -> type " + found + " (" + GSIndustryType.GetName(found) + ")"); }}
	}}
	local ok = {{ town = 0, industry = 0, sign = 0 }};
	local want = {{ town = 0, industry = 0, sign = 0 }};
	local founded = {{}};
	local ring = Ring(10);
	/* Industries search wider than towns: a 30 m terrain has fewer flat sites than the 90 m one
	 * did. A tile whose 4x4 neighbourhood is not buildable is skipped before any command is
	 * tried (a cheap read, no command), so the search stays fast; every move is recorded. */
	local RING_INDUSTRY = Ring(40);
	foreach (e in ENTITIES) {{
		want[e.kind] += 1;
		if (e.kind == "town") {{
			local done = false;
			foreach (o in ring) {{
				if (!OnMap(e.x + o[0], e.y + o[1])) continue;
				local tile = GSMap.GetTileIndex(e.x + o[0], e.y + o[1]);
				if (!GSMap.IsValidTile(tile)) continue;
				if (GSTown.FoundTown(tile, e.city ? GSTown.TOWN_SIZE_MEDIUM : GSTown.TOWN_SIZE_SMALL, e.city, GSTown.ROAD_LAYOUT_ORIGINAL, e.name)) {{
					local t = GSTile.GetClosestTown(tile);
					local tries = 0; local stuck = 0;
					while (GSTown.GetPopulation(t) < e.pop && tries < 80 && stuck < 8) {{
						local before = GSTown.GetPopulation(t);
						GSTown.ExpandTown(t, 10);
						if (GSTown.GetPopulation(t) <= before) stuck++;
						tries++;
					}}
					founded[t] <- true;
					local at = GSTown.GetLocation(t);
					local tx = GSMap.GetTileX(at), ty = GSMap.GetTileY(at);
					local labelled = GSTown.SetText(t, Note(e, tx, ty));
					GSLog.Info("rw: town ok " + e.id + " name=" + GSTown.GetName(t) + " at " + tx + "," + ty + " offset " + Abs(tx - e.x) + "," + Abs(ty - e.y) + " site=" + Site(e, tx, ty) + " population " + GSTown.GetPopulation(t) + "/" + e.pop + " " + e.evidence + " labelled=" + labelled);
					ok.town += 1; done = true; break;
				}}
			}}
			if (!done) GSLog.Warning("rw: town FAILED " + e.id + " " + GSError.GetLastErrorString());
		}} else if (e.kind == "industry") {{
			if (!(e.role in types)) {{ GSLog.Warning("rw: industry FAILED " + e.id + " role unresolved"); continue; }}
			local done = false;
			foreach (o in RING_INDUSTRY) {{
				if (!OnMap(e.x + o[0], e.y + o[1])) continue;
				local tile = GSMap.GetTileIndex(e.x + o[0], e.y + o[1]);
				if (!GSMap.IsValidTile(tile)) continue;
				if (!GSTile.IsBuildableRectangle(tile, 4, 4)) continue;
				local before = GSIndustryList();
				if (GSIndustryType.BuildIndustry(types[e.role], tile)) {{
					/* The new industry is the one the list did not have: the build tile need not be one of
					 * its tiles (layouts have holes), so GetIndustryID(tile) can miss. */
					local fresh = GSIndustryList();
					fresh.RemoveList(before);
					local labelled = false;
					local ix = e.x + o[0], iy = e.y + o[1];
					if (fresh.Count() == 1) {{
						local at = GSIndustry.GetLocation(fresh.Begin());
						ix = GSMap.GetTileX(at); iy = GSMap.GetTileY(at);
						labelled = GSIndustry.SetText(fresh.Begin(), Note(e, ix, iy));
					}}
					GSLog.Info("rw: industry ok " + e.id + " role=" + e.role + " at " + ix + "," + iy + " offset " + Abs(ix - e.x) + "," + Abs(iy - e.y) + " site=" + Site(e, ix, iy) + " " + e.evidence + " labelled=" + labelled);
					ok.industry += 1; done = true; break;
				}}
			}}
			if (!done) GSLog.Warning("rw: industry FAILED " + e.id + " " + GSError.GetLastErrorString());
		}} else {{
			local tile = GSMap.GetTileIndex(e.x, e.y);
			if (GSSign.IsValidSign(GSSign.BuildSign(tile, e.name))) {{
				GSLog.Info("rw: sign ok " + e.id + " text=" + e.name + " at " + e.x + "," + e.y + " " + e.evidence);
				ok.sign += 1;
			}} else GSLog.Warning("rw: sign FAILED " + e.id + " " + GSError.GetLastErrorString());
		}}
	}}
	local towns = GSTownList();
	/* A new game always has at least one town of the engine's own (GenerateTowns clamps to 1): give
	 * every town this script did not found a name and a text that say it is not a real place. */
	foreach (t, _ in towns) {{
		if (t in founded) continue;
		local was = GSTown.GetName(t);
		local loc = GSTown.GetLocation(t);
		GSTown.SetName(t, "Generated town " + t);
		GSTown.SetText(t, "engine-generated, not a real place (HYPOTHETICAL)");
		GSLog.Info("rw: engine town " + t + " name=" + GSTown.GetName(t) + " was=" + was + " at " + GSMap.GetTileX(loc) + "," + GSMap.GetTileY(loc) + " population " + GSTown.GetPopulation(t) + " HYPOTHETICAL");
	}}
	this.placed = true;
	GSLog.Info("rw: done towns " + ok.town + "/" + want.town + " industries " + ok.industry + "/" + want.industry + " signs " + ok.sign + "/" + want.sign + " game_towns " + towns.Count() + " game_industries " + GSIndustryList().Count() + " game_signs " + GSSignList().Count());
	foreach (t, _ in towns) GSLog.Info("rw: game town " + t + " " + GSTown.GetName(t) + " population " + GSTown.GetPopulation(t));
	while (true) this.Sleep(740);
}}
"#,
        ver = sc.tool.version,
        snap = &sc.snapshot_sha256[..16.min(sc.snapshot_sha256.len())],
        rules = r.id,
        rv = r.version,
        attr = q(&in_game_attribution(sc)),
    )
}

/// The in-game credit, built from the snapshot's sources (`scenario.attribution`), never typed here.
pub fn in_game_attribution(sc: &Scenario) -> String {
    format!("Real-world scenario of {}. {}", sc.query, sc.attribution.join(" | "))
}

/// OpenTTD's own town-data JSON (docs/importing_town_data.md, `ParseTownData` in
/// src/genworld.cpp): for the Scenario Editor's "Load town data" button, an alternative to the
/// GameScript when a person builds the scenario by hand. Proportions use the clockwise rotation.
pub fn town_data(sc: &Scenario) -> serde_json::Value {
    let n = sc.extent.map_size as f64;
    serde_json::Value::Array(
        sc.entities
            .iter()
            .filter(|e| e.game.kind == "town")
            .map(|e| {
                serde_json::json!({
                    "name": e.name,
                    "population": e.population.unwrap_or(0),
                    "city": e.city,
                    "x": crate::model::round_to((e.tile.x as f64 + 0.5) / n, 6),
                    "y": crate::model::round_to((e.tile.y as f64 + 0.5) / n, 6),
                })
            })
            .collect(),
    )
}
